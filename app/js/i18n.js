let currentLang = "en";

export function setLang(lang) {
  currentLang = lang === "ar" ? "ar" : "en";
}

export function getLang() {
  return currentLang;
}

export function t(key, vars) {
  let s = (DICT[currentLang] && DICT[currentLang][key]) ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  }
  return s;
}

/** Applies translations to any static index.html element tagged data-i18n, and sets dir/lang on <html>. */
export function applyStaticTranslations() {
  document.documentElement.setAttribute("dir", currentLang === "ar" ? "rtl" : "ltr");
  document.documentElement.setAttribute("lang", currentLang);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  // Elements whose translated string belongs on an attribute (aria-label,
  // placeholder, title, ...) rather than their text content.
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const spec = el.getAttribute("data-i18n-attr"); // "attrName:dictKey"
    const [attr, key] = spec.split(":");
    el.setAttribute(attr, t(key));
  });
}
